#!/usr/bin/env python3
"""Set up and check a local ATID CLI Proxy instance using only the Python stdlib."""

import argparse
import json
import os
from pathlib import Path
import secrets
import sys
from urllib.error import HTTPError, URLError
from urllib.request import ProxyHandler, Request, build_opener


ROOT = Path(__file__).resolve().parents[1]
DEV = ROOT / ".dev"
CONFIG = DEV / "config.yaml"
ACCESS = DEV / "access.json"


def setup(port):
    os.umask(0o077)
    DEV.mkdir(mode=0o700, exist_ok=True)
    DEV.chmod(0o700)
    if CONFIG.exists() or ACCESS.exists():
        if not CONFIG.is_file() or not ACCESS.is_file():
            raise RuntimeError("Incomplete setup: both .dev/config.yaml and .dev/access.json are required.")
        print("Existing development configuration preserved.")
        return
    for name in ("auths",):
        (DEV / name).mkdir(mode=0o700, exist_ok=True)
    client_key = "atid-dev-" + secrets.token_urlsafe(32)
    management_key = "atid-dev-admin-" + secrets.token_urlsafe(32)
    # JSON strings are also valid YAML scalars, including filesystem paths.
    quote = json.dumps
    config = f"""# Local development only. Generated by make setup; ignored by Git.
config-version: 8
server:
  host: "127.0.0.1"
  port: {port}
management:
  allow-remote: false
  secret-key: {quote(management_key)}
  disable-control-panel: false
  disable-auto-update-panel: true
access:
  api-keys:
    - {quote(client_key)}
oauth:
  auth-dir: {quote(str(DEV / 'auths'))}
observability:
  logs:
    debug: false
    logging-to-file: false
    request-log: false
    logs-max-total-size-mb: 100
"""
    access = {
        "base_url": f"http://127.0.0.1:{port}",
        "client_api_key": client_key,
        "management_key": management_key,
    }
    # Exclusive creation prevents replacing an existing developer's credentials.
    with ACCESS.open("x") as handle:
        json.dump(access, handle, indent=2)
        handle.write("\n")
    with CONFIG.open("x") as handle:
        handle.write(config)
    print(f"Development endpoint: {access['base_url']}")
    print("Private keys saved in .dev/access.json (values are not printed).")
    print("Connect a development provider with make login-claude when needed.")


def smoke():
    access = json.loads(ACCESS.read_text())
    base = access["base_url"]
    # Ignore shell HTTP proxy settings for these loopback-only checks.
    opener = build_opener(ProxyHandler({}))

    def check(path, expected, key=None):
        headers = {"Authorization": "Bearer " + key} if key else {}
        try:
            with opener.open(Request(base + path, headers=headers), timeout=5) as response:
                status, body = response.status, response.read()
        except HTTPError as error:
            status, body = error.code, error.read()
        if status != expected:
            raise RuntimeError(f"{path}: expected HTTP {expected}, received {status}")
        print(f"PASS {path}: HTTP {status} ({'authenticated' if key else 'unauthenticated'})")
        return body

    check("/healthz", 200)
    check("/v1/models", 401)
    models = json.loads(check("/v1/models", 200, access["client_api_key"]))
    if not isinstance(models.get("data"), list):
        raise RuntimeError("Model listing did not contain a data array")
    check("/v8/management/credentials", 401)
    management_key = access.get("management_key")
    if management_key:
        check("/v8/management/credentials", 200, management_key)
    else:
        print("SKIP authenticated management check: the existing key is not stored locally; verify login in the panel.")
    print(f"Available models: {len(models['data'])}. No inference requests were sent.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    setup_parser = commands.add_parser("setup")
    setup_parser.add_argument("--port", type=int, default=8318)
    commands.add_parser("smoke")
    args = parser.parse_args()
    if args.command == "setup":
        if not 1024 <= args.port <= 65535:
            parser.error("port must be between 1024 and 65535")
        setup(args.port)
    else:
        smoke()


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, ValueError, URLError) as error:
        print(f"Development setup/check failed: {error}", file=sys.stderr)
        sys.exit(1)
